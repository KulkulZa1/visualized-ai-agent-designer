// @vitest-environment node
import { describe, expect, it } from "vitest";
import { budgetTable, editBudget } from "@/evolve/schedule";

describe("editBudget: rrsi's test_schedule_matches_eq_anneal", () => {
  const T = 20;
  const [bMin, bMax] = [1, 4];

  it("equals Eq. (anneal) at every round", () => {
    for (let t = 0; t < T; t++) {
      expect(editBudget(t, T, bMin, bMax)).toBe(Math.ceil(bMin + (bMax - bMin) * 0.5 * (1 + Math.cos((Math.PI * t) / T))));
    }
  });

  it("starts at b_max, never increases, and is b_min at t = T", () => {
    const table = budgetTable(T, bMin, bMax);

    expect(table).toHaveLength(T);
    expect(table[0]).toBe(bMax);
    expect(table).toEqual([...table].sort((a, b) => b - a));
    expect(editBudget(T, T, bMin, bMax)).toBe(bMin);
  });

  it("gives the table that rrsi's own budget_table gives", () => {
    // Generated by running rrsi/schedule.py: budget_table(20, 1, 4).
    expect(budgetTable(20, 1, 4)).toEqual([4, 4, 4, 4, 4, 4, 4, 4, 3, 3, 3, 3, 3, 2, 2, 2, 2, 2, 2, 2]);
  });
});

describe("editBudget: the edges", () => {
  it("gives b_max when T is 0 or less", () => {
    expect(editBudget(5, 0, 1, 4)).toBe(4);
    expect(editBudget(5, -3, 1, 4)).toBe(4);
    expect(budgetTable(0, 1, 4)).toEqual([]);
    expect(budgetTable(-2, 1, 4)).toEqual([]);
  });

  it("clamps t to [0, T]", () => {
    // cos is even, so t = -5 would give the same budget as t = 5 and hide a missing clamp (it is 4 either way);
    // -10 would give 3 and -20 would give 1.
    expect(editBudget(-10, 20, 1, 4)).toBe(4);
    expect(editBudget(-20, 20, 1, 4)).toBe(4);
    expect(editBudget(-5, 20, 1, 4)).toBe(editBudget(0, 20, 1, 4));
    expect(editBudget(99, 20, 1, 4)).toBe(editBudget(20, 20, 1, 4));
    expect(editBudget(99, 20, 1, 4)).toBe(1);
  });

  it("is the same budget for every round when b_min = b_max", () => {
    expect(budgetTable(6, 3, 3)).toEqual([3, 3, 3, 3, 3, 3]);
  });

  it("rounds to 9 decimals before the ceiling, so floating error cannot add a whole edit", () => {
    // 1 + 4·½·(1 + cos(2π/3)) is exactly 2, but cos(2π/3) is -0.4999999999999998 in floating point and the sum is
    // 2.0000000000000004, which a bare ceiling turns into 3. rrsi gives 2.
    expect(1 + 4 * 0.5 * (1 + Math.cos((Math.PI * 2) / 3))).toBeGreaterThan(2);
    expect(editBudget(2, 3, 1, 5)).toBe(2);
  });
});
