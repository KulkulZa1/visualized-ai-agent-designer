// @vitest-environment node
import { describe, expect, it } from "vitest";
import { bootstrapSe, calibrate } from "@/evolve/calibrate";
import { aggregate, pooled, type TaskResult } from "@/evolve/measure";
import { evalOf, tenTasks } from "./evalFixture";

const alternating = Object.fromEntries(Array.from({ length: 40 }, (_, i) => [`t${i}`, [i % 2, (i + 1) % 2]])); // every task: one pass, one fail
const base40 = evalOf("base", alternating, 2); // S = 0.5

/** Ten tasks of two trials with S = 0.7: four pass twice, six pass once, so the trials of a task differ and the bootstrap has something to resample. */
const mixed70 = (job: string) =>
  evalOf(job, Object.fromEntries(Array.from({ length: 10 }, (_, i) => [`t${i}`, i < 4 ? [1, 1] : [1, 0]])), 2);

const weighted = (rewards: number[], weight: number): TaskResult => ({ rewards, weights: rewards.map(() => weight), tokens: rewards.map(() => null), missing: 0 });

/** The bootstrap is statistical: with 2000 repetitions its sd is within about 2% of the true value, and the seed makes the draw
 *  the same on every run. The bound here is 8%; a wrong formula is off by far more. */
function expectNear(actual: number, expected: number): void {
  expect(actual).toBeGreaterThan(expected * 0.92);
  expect(actual).toBeLessThan(expected * 1.08);
}

describe("calibrate: rrsi's test_calibration_bootstrap_and_repeats", () => {
  it("bootstraps one evaluation", () => {
    const cal = calibrate([base40], 2.0, 300);

    expect(cal.delta).toBeGreaterThan(0);
    expect(cal.method.startsWith("bootstrap")).toBe(true);
  });

  it("uses the repeats of two evaluations", () => {
    const second = evalOf("base2", Object.fromEntries(Array.from({ length: 40 }, (_, i) => [`t${i}`, [1, i % 3 ? 1 : 0]])), 2);
    const cal = calibrate([base40, second], 2.0, 100);

    expect(cal.n_evals).toBe(2);
    expect(cal.delta).toBeGreaterThanOrEqual(0);
  });
});

describe("calibrate: repeated base evaluations", () => {
  it("gives sd_null 0.2 and delta 0.4 for two evaluations with S 0.5 and 0.7, by hand", () => {
    // stdev([0.5, 0.7]) = √0.02 = 0.1414…; times √2 is 0.2, and delta = z · 0.2.
    const cal = calibrate([tenTasks("a", 5), tenTasks("b", 7)], 2, 300);

    expect(cal.method).toBe("repeated base evaluations");
    expect(cal.sd_null).toBe(0.2);
    expect(cal.delta).toBe(0.4);
    expect(cal.S_per_eval).toEqual([0.5, 0.7]);
    expect(cal.max_abs_diff).toBeCloseTo(0.2, 12);
  });

  it("is the same as rrsi's own calibrate on those two evaluations", () => {
    // Generated by running rrsi/calibrate.py: delta, z, sd_null, method, n_evals, k, n_tasks, S_base, C_base, S_per_eval.
    const cal = calibrate([tenTasks("a", 5), tenTasks("b", 7)], 2, 300);

    expect(cal).toMatchObject({
      delta: 0.4, z: 2, sd_null: 0.2, method: "repeated base evaluations", n_evals: 2, k: 2, n_tasks: 10, S_base: 0.5, C_base: 1000,
      S_per_eval: [0.5, 0.7],
    });
  });

  it("scales delta with z", () => {
    const cal = calibrate([tenTasks("a", 5), tenTasks("b", 7)], 3, 300);

    expect(cal.z).toBe(3);
    expect(cal.delta).toBe(0.6);
    expect(cal.sd_null).toBe(0.2);
  });

  it("uses the sample standard deviation of three, and the largest difference between any two", () => {
    const cal = calibrate([tenTasks("a", 5), tenTasks("b", 7), tenTasks("c", 6)], 2, 200);

    expect(cal.S_per_eval).toEqual([0.5, 0.7, 0.6]);
    expect(cal.sd_null).toBeCloseTo(0.1 * Math.SQRT2, 6); // stdev([0.5, 0.7, 0.6]) = 0.1
    expect(cal.delta).toBeCloseTo(2 * 0.1 * Math.SQRT2, 6);
    expect(cal.max_abs_diff).toBeCloseTo(0.2, 12);
  });

  it("falls back to the bootstrap when the repeats do not differ", () => {
    const cal = calibrate([base40, evalOf("copy", alternating, 2)], 2, 300);

    expect(cal.method).toBe("repeated base evaluations");
    expect(cal.max_abs_diff).toBe(0);
    expect(cal.sd_null).toBeGreaterThan(0.01);
    expect(cal.sd_null).toBe(cal.sd_null_bootstrap);
    expect(cal.delta).toBeCloseTo(2 * cal.sd_null_bootstrap, 5);
  });

  it("falls back to the bootstrap for three repeats of a score such as 0.7, which a plain float standard deviation puts at 1e-16", () => {
    const cal = calibrate([mixed70("a"), mixed70("b"), mixed70("c")], 2, 300);

    expect(cal.S_per_eval).toEqual([0.7, 0.7, 0.7]);
    expect(cal.max_abs_diff).toBe(0);
    expect(cal.sd_null).toBeGreaterThan(0.01); // the bootstrap's, not the repeats' 1e-16
    expect(cal.sd_null).toBe(cal.sd_null_bootstrap);
    expect(cal.delta).toBeGreaterThan(0.02);
  });

  it("bootstraps the pooled trials, with k scaled by the evaluations pooled", () => {
    const a = tenTasks("a", 5);
    const b = tenTasks("b", 7);
    const cal = calibrate([a, b], 2, 100);
    const se = bootstrapSe(pooled([a, b]), 100);

    expect(cal.se_bootstrap).toBeCloseTo(se, 6);
    expect(cal.sd_null_bootstrap).toBeCloseTo(Math.SQRT2 * se * Math.sqrt(4 / 2), 6); // pooled k is 4, the first evaluation's is 2
  });
});

describe("calibrate: one evaluation", () => {
  it("builds delta from the bootstrap: z · √2 · se", () => {
    const cal = calibrate([base40], 2, 500);

    expect(cal.method).toBe("bootstrap over trials of one base evaluation");
    expect(cal.se_bootstrap).toBeCloseTo(bootstrapSe(base40, 500), 6);
    expect(cal.sd_null_bootstrap).toBeCloseTo(Math.SQRT2 * cal.se_bootstrap, 5);
    expect(cal.sd_null).toBe(cal.sd_null_bootstrap);
    expect(cal.delta).toBeCloseTo(2 * cal.sd_null_bootstrap, 5);
  });

  it("reports the evaluation, and has no repeats to report", () => {
    const cal = calibrate([base40], 2, 100);

    expect(cal).toMatchObject({ z: 2, n_evals: 1, k: 2, n_tasks: 40, S_base: 0.5, C_base: 1000 });
    expect(cal).not.toHaveProperty("S_per_eval");
    expect(cal).not.toHaveProperty("max_abs_diff");
  });

  it("reports a cost of null when the evaluation has none", () => {
    const noTokens = aggregate("n", 1, { a: weighted([1, 0], 1) });

    expect(calibrate([noTokens], 2, 50).C_base).toBeNull();
  });

  it("scales delta with z", () => {
    const two = calibrate([base40], 2, 200);
    const three = calibrate([base40], 3, 200);

    expect(three.se_bootstrap).toBe(two.se_bootstrap);
    expect(three.delta).toBeCloseTo(1.5 * two.delta, 5);
  });

  it("gives the same result for the same inputs", () => {
    expect(calibrate([base40], 2, 200)).toEqual(calibrate([base40], 2, 200));
  });

  it("is close to what rrsi's own calibrate gives with its generator", () => {
    // Generated by running rrsi/calibrate.py on this evaluation (40 tasks, one pass and one fail each), 2000 reps, seed 7:
    // se 0.055758, delta 0.157706. Its draws differ from this port's, so only the size is compared (rrsi's own seeds 1 to 5
    // give se between 0.0545 and 0.0562).
    const cal = calibrate([base40], 2, 2000);

    expect(cal.se_bootstrap).toBeGreaterThan(0.0558 * 0.9);
    expect(cal.se_bootstrap).toBeLessThan(0.0558 * 1.1);
    expect(cal.delta).toBeGreaterThan(0.157706 * 0.9);
    expect(cal.delta).toBeLessThan(0.157706 * 1.1);
  });
});

describe("calibrate: no evaluation", () => {
  it("throws", () => {
    expect(() => calibrate([])).toThrow("no base evaluations");
  });
});

describe("bootstrapSe", () => {
  it("gives the same result for the same seed, and a different one for another", () => {
    expect(bootstrapSe(base40, 300, 7)).toBe(bootstrapSe(base40, 300, 7));
    expect(bootstrapSe(base40, 300, 8)).not.toBe(bootstrapSe(base40, 300, 7));
  });

  it("has the seed 7 and 2000 repetitions by default", () => {
    expect(bootstrapSe(base40)).toBe(bootstrapSe(base40, 2000, 7));
  });

  it("is the standard error of S: for 40 tasks of one pass and one fail it is √20 / 80 = 0.0559", () => {
    // Resampling two trials from {1, 0} gives 0, 1 or 2 passes (1/4, 1/2, 1/4): variance 1/2 per task, 20 over 40 tasks,
    // so sd(passes) = 4.47 of 80 trials.
    const se = bootstrapSe(base40, 2000);

    expect(se).toBeGreaterThan(0.0559 * 0.9);
    expect(se).toBeLessThan(0.0559 * 1.1);
  });

  it("is 0 when every trial has the same reward", () => {
    expect(bootstrapSe(evalOf("all-pass", { a: [1, 1], b: [1, 1, 1] }, 3), 300)).toBe(0);
    expect(bootstrapSe(evalOf("all-fail", { a: [0, 0], b: [0, 0] }, 2), 300)).toBe(0);
  });

  it("resamples within a task: a task of one trial cannot vary", () => {
    expect(bootstrapSe(evalOf("single", { a: [1], b: [0], c: [1] }, 1), 300)).toBe(0);
  });

  it("respects the weights in the total: a task of weight 99 that never varies leaves S little room to move", () => {
    // S = (99·4 + passes of b) / (99·4 + 4) with passes ~ Binomial(4, ½), sd 1: se = 1/400. With equal weights it is 1/8.
    const heavy = aggregate("h", 4, { a: weighted([1, 1, 1, 1], 99), b: weighted([1, 0, 1, 0], 1) });
    const equal = aggregate("e", 4, { a: weighted([1, 1, 1, 1], 1), b: weighted([1, 0, 1, 0], 1) });

    expectNear(bootstrapSe(heavy, 2000), 1 / 400);
    expectNear(bootstrapSe(equal, 2000), 1 / 8);
  });

  it("respects the weights in the sum too: two varying tasks of weight 99 and 1", () => {
    // Each task passes Binomial(4, ½) of its 4 trials (variance 1). S = (99·pa + pb) / 400 has sd √(99² + 1) / 400 = 0.2475;
    // with equal weights S = (pa + pb) / 8 has sd √2 / 8 = 0.1768.
    const varying = [1, 0, 1, 0];
    const heavy = aggregate("h", 4, { a: weighted(varying, 99), b: weighted(varying, 1) });
    const equal = aggregate("e", 4, { a: weighted(varying, 1), b: weighted(varying, 1) });

    expectNear(bootstrapSe(heavy, 2000), Math.sqrt(99 ** 2 + 1) / 400);
    expectNear(bootstrapSe(equal, 2000), Math.SQRT2 / 8);
  });

  it("is the population standard deviation of the repetitions, not the sample one", () => {
    // One task of a pass and a fail: a repetition's S is 0, 0.5 or 1. Two repetitions a and b have the population sd |a − b| / 2,
    // which is 0, 0.25 or 0.5; the sample sd |a − b| / √2 would be 0, 0.354 or 0.707. With 2000 repetitions the two are the
    // same to 0.03%, so only a handful of repetitions tell them apart.
    const ev = evalOf("one", { a: [1, 0] }, 2);
    const ses = Array.from({ length: 12 }, (_, seed) => bootstrapSe(ev, 2, seed + 1));

    for (const se of ses) expect([0, 0.25, 0.5]).toContain(se);
    expect(ses.some((se) => se > 0)).toBe(true);
  });

  it("leaves out a task with no trial", () => {
    const withEmpty = aggregate("w", 2, { ...base40.per_task, none: { rewards: [], weights: [], tokens: [], missing: 0 } });

    expect(bootstrapSe(withEmpty, 300)).toBe(bootstrapSe(base40, 300));
  });

  it("is 0 for fewer than two repetitions", () => {
    expect(bootstrapSe(base40, 1)).toBe(0);
    expect(bootstrapSe(base40, 0)).toBe(0);
  });

  it("is 0 for an evaluation with no weight at all", () => {
    expect(bootstrapSe(aggregate("z", 2, { a: weighted([1, 0], 0) }), 100)).toBe(0);
  });
});
