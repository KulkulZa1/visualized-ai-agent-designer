/** A history in a folder of its own, removed after the test. */
function newHistory(): { history: History; file: string } {
  const dir = mkdtempSync(join(tmpdir(), "evolve-history-"));
  dirs.push(dir);
  const file = join(dir, "history.jsonl");
  return { history: new History(file), file };
}

const withoutTs = (rec: HistoryRecord): Omit<HistoryRecord, "ts"> => {
  const copy = { ...rec };
  delete copy.ts;
  return copy;
};

/** rrsi's test history, with its component `skill` replaced by `client_tool`. */
function rrsiHistory(): History {
  const { history } = newHistory();
  history.appendCandidate(0, "A", [{ id: "C1", component: "prompt", hypothesis: "h1" }], "ACCEPTED", 0.03, 0.05, true, 0.53, 1000, null);
  history.appendCandidate(1, "A", [{ id: "C1", component: "prompt", hypothesis: "h2" }], "REJECTED", -0.01, 0.0, false, 0.52, 1000, null);
  history.appendCandidate(
    1, "B", [{ id: "C1", component: "client_tool", hypothesis: "h3" }, { id: "C2", component: "memory", hypothesis: "h4" }],
    "REJECTED", -0.02, 0.3, false, 0.51, 1300, null,
  );
  history.appendCandidate(2, "A", [{ id: "C1", component: "config", hypothesis: "h5" }], "critic_reject", null, null, false, null, null, null, "leak");
  return history;
}

describe("History: rrsi's test_history_summaries_prune_and_explore", () => {
  it("has tried the components with a measured edit: the critic-rejected config edit is not tried", () => {
    expect(rrsiHistory().tried()).toEqual(new Set(["prompt", "client_tool", "memory"]));
  });

  it("takes g as the best delta_S within the window", () => {
    const g = rrsiHistory().yieldG(3, 4);

    expect(g.prompt).toBe(0.03);
    expect(g.client_tool).toBe(-0.02);
    expect(g.memory).toBe(-0.02);
    expect(g.config).toBeUndefined();
  });

  it("drops an edit from g when it leaves the window: at t = 5 the accepted prompt edit of t = 0 is out", () => {
    expect(rrsiHistory().yieldG(5, 4).prompt).toBe(-0.01);
  });

  it("gives −∞ when nothing is recent", () => {
    expect(rrsiHistory().yieldG(6, 4).prompt).toBe(-Infinity);
  });

  it("prunes the tried components whose g is 0 or less, with the accepted machinery to remove", () => {
    const prune = Object.fromEntries(rrsiHistory().pruneSet(5, 4).map((p) => [p.component, p]));

    expect(Object.keys(prune).sort()).toEqual(["client_tool", "memory", "prompt"]);
    expect(prune.prompt.accepted_edits_in_incumbent[0].hypothesis).toBe("h1");
  });

  it("counts the accepted edits per component for the incumbent", () => {
    expect(rrsiHistory().incumbentComponentCounts().prompt).toBe(1);
  });

  it("has novelty over those counts: a subagent edit is new, a client_tool edit with two accepted is not", () => {
    // rrsi: novelty(["client_tool", "prompt"], counts) == 1 and novelty(["skill"], {"skill": 2}) == 0.
    expect(novelty(["subagent", "prompt"], rrsiHistory().incumbentComponentCounts())).toBe(1);
    expect(novelty(["client_tool"], { client_tool: 2 })).toBe(0);
  });

  it("knows which variants a round has written", () => {
    const history = rrsiHistory();

    expect(history.has(1, "B")).toBe(true);
    expect(history.has(5, "A")).toBe(false);
    expect(history.has(1, "C")).toBe(false);
    expect(history.has(2, "A")).toBe(true); // a gate failure is a record too
  });
});

