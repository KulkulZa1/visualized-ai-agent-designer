describe("stallFlag: rrsi's cases", () => {
  const traj = [0.50, 0.53, 0.53, 0.535, 0.60];

  it("is 0 when the incumbent gained more than delta over the window", () => {
    expect(stallFlag(traj, 3, 3, 0.02)).toBe(0); // 0.535 − 0.50 = 0.035 > 0.02
  });

  it("is 1 when the gain is at most delta", () => {
    expect(stallFlag(traj, 3, 2, 0.02)).toBe(1); // 0.535 − 0.53 = 0.005 ≤ 0.02
  });

  it("is 0 again after a gain", () => {
    expect(stallFlag(traj, 4, 2, 0.02)).toBe(0); // 0.60 − 0.53 = 0.07
  });

  it("is 0 while fewer than w rounds exist", () => {
    expect(stallFlag(traj, 1, 3, 0.02)).toBe(0); // not enough history
  });
});

describe("stallFlag: the edges", () => {
  it("is 1 for a gain of exactly delta", () => {
    expect(stallFlag([0.5, 0.75], 1, 1, 0.25)).toBe(1);
  });

  it("is 1 for a fall", () => {
    expect(stallFlag([0.6, 0.5], 1, 1, 0.02)).toBe(1);
  });

  it("is 0 beyond the end of the trajectory", () => {
    expect(stallFlag([0.5, 0.5, 0.5], 3, 2, 0.02)).toBe(0);
    expect(stallFlag([], 0, 1, 0.02)).toBe(0);
  });

  it("starts at t = w, the first round with w earlier ones", () => {
    expect(stallFlag([0.5, 0.5, 0.5, 0.5], 2, 2, 0.02)).toBe(1);
    expect(stallFlag([0.5, 0.5, 0.5, 0.5], 1, 2, 0.02)).toBe(0);
  });
});

describe("exploration", () => {
  it("reserves slots when stalled: rrsi's case (σ = 1, prompt tried)", () => {
    const e = exploration(3, 1, new Set(["prompt"]), 1);

    expect(e.sigma).toBe(1);
    expect(e.untried).not.toContain("prompt");
    expect(e.text).toContain("RESERVED");
  });

  it("lists the untried components in the order of K, as JSON", () => {
    const e = exploration(3, 1, new Set(["prompt", "memory"]), 2);

    expect(e.untried).toEqual(["config", "control_flow", "context_mgmt", "client_tool", "subagent"]);
    expect(e.m_draft).toBe(2);
    expect(e.text).toBe(
      "STALL: the incumbent has not moved by more than the noise band over the last rounds (sigma_t = 1). 2 candidate slot(s) " +
      'this round are RESERVED for exploratory edits on components the run has never exercised: ["config","control_flow","context_mgmt","client_tool","subagent"]. ' +
      "A variant holding a reserved slot must put at least one edit on one of those components.",
    );
  });

  it("only mentions the untried components when not stalled", () => {
    const e = exploration(3, 0, new Set(["prompt", "config", "control_flow", "context_mgmt"]), 1);

    expect(e.sigma).toBe(0);
    expect(e.untried).toEqual(["memory", "client_tool", "subagent"]);
    expect(e.text).toBe(
      'Components not yet exercised in this run: ["memory","client_tool","subagent"]. Not mandatory this round (sigma_t = 0), ' +
      "but evidence about them is still missing.",
    );
    expect(e.text).not.toContain("RESERVED");
  });

  it("says every component has been exercised when none is untried, stalled or not", () => {
    const all = new Set<string>(K);

    for (const stall of [0, 1]) {
      const e = exploration(3, stall, all, 1);

      expect(e.untried).toEqual([]);
      expect(e.text).toBe("Every component in K has been exercised at least once.");
      expect(e.sigma).toBe(stall);
    }
  });

  it("lists all of K as untried when nothing has been tried", () => {
    expect(exploration(0, 0, new Set(), 1).untried).toEqual([...K]);
  });

  it("ignores a tried name that is not a component", () => {
    expect(exploration(0, 0, new Set(["skill"]), 1).untried).toEqual([...K]);
  });

  it("takes the tried components straight from a history, as the loop does", () => {
    const e = exploration(3, 1, rrsiHistory().tried(), 1); // prompt, client_tool and memory are tried

    expect(e.untried).toEqual(["config", "control_flow", "context_mgmt", "subagent"]);
  });
});

