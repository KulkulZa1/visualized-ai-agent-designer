import { describe, expect, it } from "vitest";
import { attribute } from "@/evolve/attribution";
import type { EditRecord } from "@/evolve/selection";
import { evalOf } from "./evalFixture";

// k = 2, so a task regressed when its mean fell by at least 1/2.
const inc = evalOf("inc", { t1: [1, 1], t2: [0, 0], t3: [1, 0], t4: [1, 1] }, 2); // means 1, 0, 0.5, 1
const cand = evalOf("cand", { t1: [1, 1], t2: [1, 0], t3: [0, 0], t4: [0, 1] }, 2); // means 1, 0.5, 0, 0.5

const edit = (predicted: unknown[] | undefined, extra: EditRecord = {}): EditRecord => ({ id: "C1", component: "prompt", hypothesis: "hyp", predicted_affected: predicted, ...extra });

describe("attribute: what an edit predicted against what the evaluation found", () => {
  it("counts the predicted tasks whose mean rose as hits, and gives the hit rate to 2 places", () => {
    const [row] = attribute(4, "A", [edit(["t1", "t2", "t3"])], inc, cand, 2);

    expect(row.n_predicted).toBe(3);
    expect(row.predicted_hit).toEqual(["t2"]); // t1 is level, t3 fell
    expect(row.hit_rate).toBe(0.33);
  });

  it("gives hit_rate null when nothing is predicted", () => {
    expect(attribute(4, "A", [edit([])], inc, cand, 2)[0]).toMatchObject({ n_predicted: 0, predicted_hit: [], hit_rate: null });
    expect(attribute(4, "A", [edit(undefined)], inc, cand, 2)[0]).toMatchObject({ n_predicted: 0, hit_rate: null });
    expect(attribute(4, "A", [edit(null as unknown as undefined)], inc, cand, 2)[0]).toMatchObject({ n_predicted: 0, hit_rate: null });
  });

  it("gives 1 for all hits and 0 for none", () => {
    expect(attribute(4, "A", [edit(["t2"])], inc, cand, 2)[0].hit_rate).toBe(1);
    expect(attribute(4, "A", [edit(["t1", "t3"])], inc, cand, 2)[0].hit_rate).toBe(0);
  });

  it("rounds the hit rate: 1 of 3 is 0.33, 2 of 3 is 0.67", () => {
    const base = evalOf("b", { a: [0], b: [0], c: [0] }, 1);
    const better = evalOf("c", { a: [1], b: [1], c: [0] }, 1);

    expect(attribute(0, "A", [edit(["a", "b", "c"])], base, better, 1)[0].hit_rate).toBe(0.67);
    expect(attribute(0, "A", [edit(["a", "c", "c"])], base, better, 1)[0].hit_rate).toBe(0.33);
  });

  it("counts a predicted task that fell as neither a hit nor an unpredicted regression", () => {
    const [row] = attribute(4, "A", [edit(["t3"])], inc, cand, 2);

    expect(row.predicted_hit).toEqual([]);
    expect(row.unpredicted_regressions).toEqual(["t4"]); // t3 fell too, but it was predicted
  });

  it("is rrsi's attribute on this evaluation", () => {
    // Generated by running rrsi/loop.py's Run.attribute. Its row for an edit without a hypothesis has the string "None"; this has null.
    const rows = attribute(4, "A", [
      { id: "C1", component: "prompt", hypothesis: "hyp", predicted_affected: ["t1", "t2", "t3", "ghost"] },
      { id: "C2", component: "config" },
      { id: "C3", hypothesis: "y".repeat(200), predicted_affected: ["t2", "t2"] },
    ], inc, cand, 2);

    expect(rows).toEqual([
      { t: 4, variant: "A", edit_id: "C1", component: "prompt", hypothesis: "hyp", n_predicted: 3, predicted_hit: ["t2"], hit_rate: 0.33, unpredicted_regressions: ["t4"] },
      { t: 4, variant: "A", edit_id: "C2", component: "config", hypothesis: null, n_predicted: 0, predicted_hit: [], hit_rate: null, unpredicted_regressions: ["t3", "t4"] },
      {
        t: 4, variant: "A", edit_id: "C3", component: null, hypothesis: "y".repeat(160), n_predicted: 2, predicted_hit: ["t2", "t2"], hit_rate: 1,
        unpredicted_regressions: ["t3", "t4"],
      },
    ]);
  });

  it("counts a task listed twice twice, as rrsi does", () => {
    const [row] = attribute(4, "A", [edit(["t2", "t2", "t3"])], inc, cand, 2);

    expect(row.n_predicted).toBe(3);
    expect(row.predicted_hit).toEqual(["t2", "t2"]);
    expect(row.hit_rate).toBe(0.67);
  });
});

describe("attribute: the threshold 1/k", () => {
  /** One task whose mean falls from `before` to `after`, k trials each; the edit predicts nothing. */
  function regressed(k: number, before: number, after: number): string[] {
    const a = evalOf("a", { x: Array(k).fill(before) }, k);
    const b = evalOf("b", { x: Array(k).fill(after) }, k);
    return attribute(0, "A", [edit([])], a, b, k)[0].unpredicted_regressions;
  }

  it("counts a drop of exactly 1/k: with k = 2, from 1 to 0.5", () => {
    expect(regressed(2, 1, 0.5)).toEqual(["x"]);
  });

  it("counts a drop of more than 1/k, and not one of less", () => {
    expect(regressed(2, 1, 0)).toEqual(["x"]);
    expect(regressed(2, 1, 0.75)).toEqual([]); // 0.25 < 0.5
  });

  it("scales with k: a drop of 0.25 counts for k = 4 and a drop of 0.125 does not", () => {
    expect(regressed(4, 1, 0.75)).toEqual(["x"]);
    expect(regressed(4, 1, 0.875)).toEqual([]);
  });

  it("is 1 for k = 1, so only the loss of the whole trial counts", () => {
    expect(regressed(1, 1, 0)).toEqual(["x"]);
    expect(regressed(1, 1, 0.5)).toEqual([]);
  });

  it("is 1 for a k below 1, as 1/max(1, k)", () => {
    const a = evalOf("a", { x: [1] }, 1);
    const b = evalOf("b", { x: [0.5] }, 1);

    expect(attribute(0, "A", [edit([])], a, b, 0)[0].unpredicted_regressions).toEqual([]);
    expect(attribute(0, "A", [edit([])], a, evalOf("c", { x: [0] }, 1), 0)[0].unpredicted_regressions).toEqual(["x"]);
  });

  it("does not count a rise, or a task that did not move", () => {
    expect(regressed(2, 0, 1)).toEqual([]);
    expect(regressed(2, 0.5, 0.5)).toEqual([]);
  });
});

describe("attribute: unpredicted regressions", () => {
  it("lists the tasks that fell and were not predicted, in the incumbent's order", () => {
    expect(attribute(4, "A", [edit(["t1"])], inc, cand, 2)[0].unpredicted_regressions).toEqual(["t3", "t4"]);
  });

  it("lists at most 12", () => {
    const ids = Array.from({ length: 15 }, (_, i) => `task${String(i).padStart(2, "0")}`);
    const up = evalOf("up", Object.fromEntries(ids.map((id) => [id, [1, 1]])), 2);
    const down = evalOf("down", Object.fromEntries(ids.map((id) => [id, [0, 0]])), 2);
    const [row] = attribute(0, "A", [edit([])], up, down, 2);

    expect(row.unpredicted_regressions).toHaveLength(12);
    expect(row.unpredicted_regressions).toEqual(ids.slice(0, 12));
  });

  it("applies the cap after leaving out the predicted ones", () => {
    const ids = Array.from({ length: 15 }, (_, i) => `task${String(i).padStart(2, "0")}`);
    const up = evalOf("up", Object.fromEntries(ids.map((id) => [id, [1, 1]])), 2);
    const down = evalOf("down", Object.fromEntries(ids.map((id) => [id, [0, 0]])), 2);
    const [row] = attribute(0, "A", [edit(ids.slice(0, 5))], up, down, 2);

    expect(row.unpredicted_regressions).toEqual(ids.slice(5, 15).slice(0, 12)); // 10 are left, all listed
    expect(row.n_predicted).toBe(5);
  });

  it("gives each row its own list", () => {
    const rows = attribute(4, "A", [edit([]), edit([])], inc, cand, 2);
    rows[0].unpredicted_regressions.push("changed");

    expect(rows[1].unpredicted_regressions).toEqual(["t3", "t4"]);
  });

  it("does not count a task that only one evaluation ran", () => {
    const a = evalOf("a", { x: [1, 1], onlyInc: [1, 1] }, 2);
    const b = evalOf("b", { x: [1, 1], onlyCand: [0, 0] }, 2);

    expect(attribute(0, "A", [edit([])], a, b, 2)[0].unpredicted_regressions).toEqual([]);
  });
});

describe("attribute: predicted tasks that are not in both evaluations", () => {
  const a = evalOf("a", { x: [0, 0], onlyInc: [0, 0] }, 2);
  const b = evalOf("b", { x: [1, 1], onlyCand: [1, 1] }, 2);

  it("ignores a predicted task missing from the candidate's evaluation, from the incumbent's, or from both", () => {
    const [row] = attribute(0, "A", [edit(["x", "onlyInc", "onlyCand", "nowhere"])], a, b, 2);

    expect(row.n_predicted).toBe(1);
    expect(row.predicted_hit).toEqual(["x"]);
    expect(row.hit_rate).toBe(1);
  });

  it("has no hit rate when every predicted task is missing", () => {
    const [row] = attribute(0, "A", [edit(["onlyInc", "onlyCand", "nowhere"])], a, b, 2);

    expect(row).toMatchObject({ n_predicted: 0, predicted_hit: [], hit_rate: null });
  });

  it("reads the predicted ids as strings: a number matches the task of that name", () => {
    const numbered = evalOf("n", { 1: [0], 2: [0], 3: [0] }, 1);
    const risen = evalOf("r", { 1: [1], 2: [0], 3: [1] }, 1);
    const [row] = attribute(0, "A", [edit([1, 2, 3, 4])], numbered, risen, 1);

    expect(row.n_predicted).toBe(3);
    expect(row.predicted_hit).toEqual(["1", "3"]);
  });

  it("does not take a name every object has for a task", () => {
    const [row] = attribute(0, "A", [edit(["constructor", "toString", "__proto__", "hasOwnProperty", "valueOf"])], a, b, 2);

    expect(row).toMatchObject({ n_predicted: 0, predicted_hit: [], hit_rate: null });
  });

  it("still finds a task that really has such a name", () => {
    const odd = evalOf("o", { constructor: [0], toString: [0] }, 1);
    const oddUp = evalOf("p", { constructor: [1], toString: [0] }, 1);
    const [row] = attribute(0, "A", [edit(["constructor", "toString"])], odd, oddUp, 1);

    expect(row.n_predicted).toBe(2);
    expect(row.predicted_hit).toEqual(["constructor"]);
  });
});

describe("attribute: the rows", () => {
  it("gives one row per edit, in order, with the round, the variant, the id and the component", () => {
    const rows = attribute(7, "B", [{ id: "C1", component: "memory" }, { id: "C2", component: "config" }, {}], inc, cand, 2);

    expect(rows.map((r) => [r.t, r.variant, r.edit_id, r.component])).toEqual([[7, "B", "C1", "memory"], [7, "B", "C2", "config"], [7, "B", null, null]]);
  });

  it("gives no rows for no edits", () => {
    expect(attribute(0, "A", [], inc, cand, 2)).toEqual([]);
  });

  it("cuts the hypothesis to 160 characters and keeps a shorter one whole", () => {
    const rows = attribute(0, "A", [{ id: "C1", hypothesis: "z".repeat(161) }, { id: "C2", hypothesis: "z".repeat(160) }, { id: "C3", hypothesis: "short" }], inc, cand, 2);

    expect(rows.map((r) => r.hypothesis?.length)).toEqual([160, 160, 5]);
  });

  it("cuts the hypothesis by characters: it never splits an emoji in half", () => {
    const [row] = attribute(0, "A", [{ id: "C1", hypothesis: `${"a".repeat(159)}😀${"b".repeat(20)}` }], inc, cand, 2);

    expect(row.hypothesis).toBe(`${"a".repeat(159)}😀`);
  });

  it("gives hypothesis null when the edit has none, and '' when it is empty", () => {
    const rows = attribute(0, "A", [{ id: "C1" }, { id: "C2", hypothesis: null }, { id: "C3", hypothesis: "" }], inc, cand, 2);

    expect(rows.map((r) => r.hypothesis)).toEqual([null, null, ""]);
  });

  it("does not take the mechanism for the hypothesis: only the history does", () => {
    expect(attribute(0, "A", [{ id: "C1", mechanism: "m" }], inc, cand, 2)[0].hypothesis).toBeNull();
  });

  it("changes none of its inputs", () => {
    const before = JSON.stringify([inc, cand]);
    const edits: EditRecord[] = [edit(["t1", "t2"])];
    const editsBefore = JSON.stringify(edits);
    attribute(0, "A", edits, inc, cand, 2);

    expect(JSON.stringify([inc, cand])).toBe(before);
    expect(JSON.stringify(edits)).toBe(editsBefore);
  });
});
