import { describe, expect, it } from "vitest";
import { DEFAULT_CONFIG, type EvolveConfig } from "@/evolve/config";
import { candidateComponents, costRule, judge, selectRound, type Candidate } from "@/evolve/selection";
import type { EvalResult } from "@/evolve/measure";
import { evalOf, tenTasks } from "./evalFixture";

const cfg: EvolveConfig = { ...DEFAULT_CONFIG, beta0: 0.1, beta1: 40.0, w_s: 100.0, w_c: 15.0, w_n: 0.5 };

const cand = (variant: string, component: string, ev: EvalResult): Candidate => ({ variant, edits: [{ id: "C1", component }], ev });

describe("costRule: rrsi's test_cost_rule_both_branches", () => {
  it("lets a gain through within the budget beta0 + beta1·ΔS, and stops it over", () => {
    expect(costRule(0.05, 0.10 + 40 * 0.05 - 0.01, 0, 0.02, cfg)[0]).toBe(true); // within budget
    expect(costRule(0.05, 0.10 + 40 * 0.05 + 0.01, 0, 0.02, cfg)[0]).toBe(false); // over budget
  });

  it("inside the band, takes the shaped rule: cheaper passes, costlier fails, a new structural component breaks the tie", () => {
    expect(costRule(0.0, -0.10, 0, 0.02, cfg)[0]).toBe(true); // neutral, cheaper
    expect(costRule(0.0, 0.10, 0, 0.02, cfg)[0]).toBe(false); // neutral, costlier
    expect(costRule(0.0, 0.0, 1, 0.02, cfg)[0]).toBe(true); // neutral, new structural
  });

  it("takes the first branch only for a gain above delta: a gain of exactly delta is inside the band", () => {
    expect(costRule(0.02, 0.0, 0, 0.02, cfg)[1]).toContain("within delta");
    expect(costRule(0.021, 0.0, 0, 0.02, cfg)[1]).toContain("> delta");
  });

  it("is not satisfied by a neutral candidate that costs nothing and brings nothing: shaped must be above 0", () => {
    expect(costRule(0.0, 0.0, 0, 0.02, cfg)[0]).toBe(false);
  });
});

describe("costRule: the reason texts", () => {
  // Generated by running rrsi/selection.py's cost_rule with this config. The numbers beta1, w_s and w_c print as 40, 100 and 15
  // here where Python prints its floats as 40.0, 100.0 and 15.0.
  it("gives rrsi's text for a gain within the budget and over it", () => {
    expect(costRule(0.05, 0.10 + 40 * 0.05 - 0.01, 0, 0.02, cfg)).toEqual([
      true, "gain +0.0500 > delta 0.0200; cost change +2.090 <= budget 2.100 (beta0 0.1 + beta1 40 * dS)",
    ]);
    expect(costRule(0.05, 0.10 + 40 * 0.05 + 0.01, 0, 0.02, cfg)).toEqual([
      false, "gain +0.0500 > delta 0.0200; cost change +2.110 > budget 2.100 (beta0 0.1 + beta1 40 * dS)",
    ]);
  });

  it("gives rrsi's text for the shaped rule, with the sign of every figure", () => {
    expect(costRule(0.0, -0.10, 0, 0.02, cfg)).toEqual([
      true, "gain +0.0000 within delta 0.0200; shaped 100*dS - 15*dC + 0.5*nu = +1.5000 > 0 (nu=0)",
    ]);
    expect(costRule(0.0, 0.10, 0, 0.02, cfg)).toEqual([
      false, "gain +0.0000 within delta 0.0200; shaped 100*dS - 15*dC + 0.5*nu = -1.5000 <= 0 (nu=0)",
    ]);
    expect(costRule(0.0, 0.0, 1, 0.02, cfg)).toEqual([
      true, "gain +0.0000 within delta 0.0200; shaped 100*dS - 15*dC + 0.5*nu = +0.5000 > 0 (nu=1)",
    ]);
    expect(costRule(-0.01, 0.2, 0, 0.02, cfg)).toEqual([
      false, "gain -0.0100 within delta 0.0200; shaped 100*dS - 15*dC + 0.5*nu = -4.0000 <= 0 (nu=0)",
    ]);
  });

  it("writes a figure that is exactly a half as Python does: to the even digit", () => {
    // Generated by running rrsi/selection.py's cost_rule. 0.28125 and 0.03125 are exact in binary, so they are exact halves at 4 places.
    expect(costRule(0.28125, 0.0, 0, 0.0, cfg)).toEqual([true, "gain +0.2812 > delta 0.0000; cost change +0.000 <= budget 11.350 (beta0 0.1 + beta1 40 * dS)"]);
    expect(costRule(-0.03125, 0.09375, 0, 0.5, cfg)).toEqual([
      false, "gain -0.0312 within delta 0.5000; shaped 100*dS - 15*dC + 0.5*nu = -4.5312 <= 0 (nu=0)",
    ]);
    expect(costRule(0.0, 0.0, 1, 0.03125, cfg)).toEqual([
      true, "gain +0.0000 within delta 0.0312; shaped 100*dS - 15*dC + 0.5*nu = +0.5000 > 0 (nu=1)",
    ]);
  });

  it("writes the budget that is exactly a half as Python does", () => {
    // 0.25 + 0.5 · 0.125 = 0.3125, an exact half at 3 places.
    expect(costRule(0.125, 0.0, 0, 0.02, { ...cfg, beta0: 0.25, beta1: 0.5 })).toEqual([
      true, "gain +0.1250 > delta 0.0200; cost change +0.000 <= budget 0.312 (beta0 0.25 + beta1 0.5 * dS)",
    ]);
  });

  it("writes the sign of a figure that rounds to zero, as Python's + format does", () => {
    expect(costRule(-0.00001, 0.0, 0, 0.02, cfg)[1]).toContain("gain -0.0000 within");
    expect(costRule(0.0, 0.0, 0, 0.02, cfg)[1]).toContain("gain +0.0000 within");
  });
});

describe("selectRound: rrsi's test_selection_floor_argmax_and_sstar", () => {
  // The incumbent has S = 0.5. S* is above it (an earlier peak). rrsi's component `skill` is `client_tool` here.
  const inc = tenTasks("inc", 5);
  const S_star = 0.55;
  const delta = 0.05;
  const a = cand("A", "prompt", tenTasks("A", 7)); // S 0.7
  const b = cand("B", "client_tool", tenTasks("B", 6)); // S 0.6
  const c = cand("C", "config", tenTasks("C", 3)); // S 0.3, under the floor
  const d: Candidate = { variant: "D", edits: [], gate_failure: "critic_reject" };

  it("picks the admissible candidate with the highest S, and explains the others", () => {
    const { winner, decisions } = selectRound([a, b, c, d], inc, S_star, delta, cfg, {}, undefined);
    const by = Object.fromEntries(decisions.map((x) => [x.variant, x]));

    expect(winner).toBe(a);
    expect(by.A.admissible).toBe(true);
    expect(by.B.admissible).toBe(true);
    expect(by.C.admissible).toBe(false);
    expect(by.C.reason).toContain("floor");
    expect(by.D.admissible).toBe(false);
    expect(by.D.reason).toBe("critic_reject");
  });

  it("returns one decision per candidate, in the order given", () => {
    const { decisions } = selectRound([a, b, c, d], inc, S_star, delta, cfg, {});

    expect(decisions.map((x) => x.variant)).toEqual(["A", "B", "C", "D"]);
  });

  it("gives rrsi's decisions: the figures and the reasons", () => {
    const { decisions } = selectRound([a, c, d], inc, S_star, delta, cfg, {});

    expect(decisions[0]).toMatchObject({
      variant: "A", admissible: true, S: 0.7, C: 1000, delta_C: 0, novelty: 0, guards: [],
      reason: "admissible: gain +0.2000 > delta 0.0500; cost change +0.000 <= budget 8.100 (beta0 0.1 + beta1 40 * dS)",
    });
    expect(decisions[0].delta_S).toBeCloseTo(0.2, 12);
    expect(decisions[1]).toMatchObject({
      variant: "C", admissible: false, S: 0.3, delta_C: 0, novelty: 0,
      reason: "below noise-adjusted floor: S' 0.3000 < S* 0.5500 - delta 0.0500",
    });
    expect(decisions[1].delta_S).toBeCloseTo(-0.2, 12);
    expect(decisions[2]).toEqual({ variant: "D", admissible: false, reason: "critic_reject", novelty: 0, guards: [] });
  });

  it("blocks a gaining candidate that is too expensive with the cost rule", () => {
    // The same score as A at 1 + beta0 + beta1·0.2 + 0.5 times the incumbent's tokens: over the budget beta0 + beta1·ΔS.
    const expensive = cand("E", "prompt", tenTasks("E", 7, 1000 * (1 + 0.1 + 40 * 0.2 + 0.5)));
    const { winner, decisions } = selectRound([expensive], inc, S_star, delta, cfg, {});

    expect(winner).toBeNull();
    expect(decisions[0].reason).toContain("cost rule");
    expect(decisions[0].reason).toBe(
      "cost rule failed: gain +0.2000 > delta 0.0500; cost change +8.600 > budget 8.100 (beta0 0.1 + beta1 40 * dS)",
    );
  });

  it("treats a domain guard as non-compensatory", () => {
    const { winner, decisions } = selectRound([a], inc, S_star, delta, cfg, {}, () => ["valid rate fell"]);

    expect(winner).toBeNull();
    expect(decisions[0].reason).toContain("guard");
    expect(decisions[0].reason).toBe("domain guard violated: valid rate fell");
    expect(decisions[0].guards).toEqual(["valid rate fell"]);
  });

  it("lists every guard that fired", () => {
    const { decisions } = selectRound([a], inc, S_star, delta, cfg, {}, () => ["valid rate fell", "second"]);

    expect(decisions[0].reason).toBe("domain guard violated: valid rate fell; second");
  });

  it("falls to the next admissible candidate when the best scorer is stopped by a guard", () => {
    const { winner } = selectRound([a, b], inc, S_star, delta, cfg, {}, (_inc, ev) => (ev.S > 0.65 ? ["too good"] : []));

    expect(winner).toBe(b);
  });

  it("returns no winner for no candidate", () => {
    expect(selectRound([], inc, S_star, delta, cfg, {})).toEqual({ winner: null, decisions: [] });
  });

  it("returns no winner when none is admissible", () => {
    const { winner, decisions } = selectRound([c, d], inc, S_star, delta, cfg, {});

    expect(winner).toBeNull();
    expect(decisions.every((x) => !x.admissible)).toBe(true);
  });
});

describe("selectRound: ties and order", () => {
  const inc = tenTasks("inc", 5);
  const first = cand("A", "prompt", tenTasks("A", 7));
  const second = cand("B", "config", tenTasks("B", 7)); // the same score as A

  it("keeps the first on a tie, as Python's max does", () => {
    expect(selectRound([first, second], inc, 0.5, 0.05, cfg, {}).winner).toBe(first);
  });

  it("keeps the first of the list on a tie, whatever its label", () => {
    expect(selectRound([second, first], inc, 0.5, 0.05, cfg, {}).winner).toBe(second);
  });

  it("keeps the first on a tie among three", () => {
    const third = cand("C", "memory", tenTasks("C", 7));

    expect(selectRound([second, third, first], inc, 0.5, 0.05, cfg, {}).winner).toBe(second);
  });

  it("is not the last-best: a later candidate wins only with a higher S", () => {
    const better = cand("C", "prompt", tenTasks("C", 8));

    expect(selectRound([first, second, better], inc, 0.5, 0.05, cfg, {}).winner).toBe(better);
    expect(selectRound([better, first, second], inc, 0.5, 0.05, cfg, {}).winner).toBe(better);
  });

  it("does not pick an inadmissible candidate with the best score", () => {
    const costly = cand("E", "prompt", tenTasks("E", 9, 1000 * 50)); // S 0.9 at 50 times the tokens
    const { winner, decisions } = selectRound([costly, first], inc, 0.5, 0.05, cfg, {});

    expect(decisions[0].admissible).toBe(false);
    expect(winner).toBe(first);
  });
});

describe("judge: the floor, then the cost rule, then the guards", () => {
  const inc = tenTasks("inc", 5);

  it("measures the floor from S*, not from the incumbent: a gain over the incumbent can still be under the floor", () => {
    const d = judge(cand("A", "prompt", tenTasks("A", 6)), inc, 0.9, 0.1, cfg, {}); // S 0.6 > the incumbent's 0.5, but S* − delta is 0.8

    expect(d.admissible).toBe(false);
    expect(d.reason).toBe("below noise-adjusted floor: S' 0.6000 < S* 0.9000 - delta 0.1000");
  });

  it("writes the floor's figures as Python does when they are exact halves", () => {
    // S' = 9/32 = 0.28125, S* = 17/32 = 0.53125 and delta = 1/32 = 0.03125 are exact halves at 4 places. Generated by running
    // rrsi/selection.py's judge.
    const rewards = Object.fromEntries(Array.from({ length: 16 }, (_, i) => [`t${i}`, i < 4 ? [1, 1] : i === 4 ? [1, 0] : [0, 0]]));
    const low = cand("A", "prompt", evalOf("A", rewards, 2));

    expect(low.ev?.S).toBe(0.28125);
    expect(judge(low, inc, 0.53125, 0.03125, cfg, {}).reason).toBe("below noise-adjusted floor: S' 0.2812 < S* 0.5312 - delta 0.0312");
  });

  it("includes the floor itself", () => {
    // S* − delta = 0.75 − 0.25 = 0.5 exactly; the candidate has S = 0.5 and is cheaper (ΔC = −0.1), so the shaped rule holds.
    const atFloor = cand("A", "prompt", tenTasks("A", 5, 900));

    expect(judge(atFloor, inc, 0.75, 0.25, cfg, {}).admissible).toBe(true);
    expect(judge(cand("B", "prompt", tenTasks("B", 4, 900)), inc, 0.75, 0.25, cfg, {}).reason).toContain("below noise-adjusted floor");
  });

  it("reports the floor before the cost rule when both fail", () => {
    const d = judge(cand("A", "prompt", tenTasks("A", 3, 100000)), inc, 0.55, 0.05, cfg, {});

    expect(d.reason).toMatch(/^below noise-adjusted floor/);
  });

  it("reports the cost rule before the guards when both fail, and still records the guards", () => {
    const d = judge(cand("A", "prompt", tenTasks("A", 7, 1000 * 50)), inc, 0.55, 0.05, cfg, {}, ["g1"]);

    expect(d.reason).toMatch(/^cost rule failed/);
    expect(d.guards).toEqual(["g1"]);
    expect(d.admissible).toBe(false);
  });

  it("reports the floor before the guards when both fail", () => {
    const d = judge(cand("A", "prompt", tenTasks("A", 3)), inc, 0.55, 0.05, cfg, {}, ["g1"]);

    expect(d.reason).toMatch(/^below noise-adjusted floor/);
  });

  it("uses the novelty of its edits in the shaped rule: a new structural component admits a neutral candidate", () => {
    const neutral = cand("A", "client_tool", tenTasks("A", 5)); // ΔS = 0, ΔC = 0

    const novel = judge(neutral, inc, 0.5, 0.05, cfg, {});
    const known = judge(neutral, inc, 0.5, 0.05, cfg, { client_tool: 1 });

    expect(novel).toMatchObject({ admissible: true, novelty: 1 });
    expect(novel.reason).toBe("admissible: gain +0.0000 within delta 0.0500; shaped 100*dS - 15*dC + 0.5*nu = +0.5000 > 0 (nu=1)");
    expect(known).toMatchObject({ admissible: false, novelty: 0 });
    expect(known.reason).toMatch(/^cost rule failed: gain \+0\.0000 within delta/);
  });

  it("counts novelty over the distinct structural components of all the edits", () => {
    const bundle: Candidate = {
      variant: "A", ev: tenTasks("A", 5),
      edits: [{ id: "C1", component: "memory" }, { id: "C2", component: "subagent" }, { id: "C3", component: "memory" }, { id: "C4", component: "prompt" }],
    };

    expect(judge(bundle, inc, 0.5, 0.05, cfg, {}).novelty).toBe(2);
    expect(judge(bundle, inc, 0.5, 0.05, cfg, { memory: 3 }).novelty).toBe(1);
  });

  it("gives the gate failure as the reason of a candidate with no evaluation, and 'not evaluated' without one", () => {
    expect(judge({ variant: "A", edits: [], gate_failure: "smoke_fail" }, inc, 0.5, 0.05, cfg, {}).reason).toBe("smoke_fail");
    expect(judge({ variant: "A", edits: [] }, inc, 0.5, 0.05, cfg, {}).reason).toBe("not evaluated");
    expect(judge({ variant: "A", edits: [], gate_failure: "" }, inc, 0.5, 0.05, cfg, {}).reason).toBe("not evaluated");
  });

  it("never admits a candidate with no evaluation", () => {
    expect(judge({ variant: "A", edits: [], gate_failure: "eval_invalid" }, inc, 0.5, 0.05, cfg, {}).admissible).toBe(false);
  });

  it("measures ΔC against the incumbent's cost, and as 0 when either side has none", () => {
    const noCost = { ...tenTasks("n", 7), C: null } satisfies EvalResult;
    const d = judge(cand("A", "prompt", noCost), inc, 0.5, 0.05, cfg, {});

    expect(d.delta_C).toBe(0);
    expect(d.C).toBeNull();
    expect(d.admissible).toBe(true);
  });
});

describe("selectRound: the guard function", () => {
  const inc = tenTasks("inc", 5);

  it("is called with the incumbent and the candidate's evaluation, and only for a candidate that has one", () => {
    const evA = tenTasks("A", 7);
    const calls: Array<[EvalResult, EvalResult]> = [];
    const gate: Candidate = { variant: "D", edits: [], gate_failure: "critic_reject" };

    selectRound([cand("A", "prompt", evA), gate], inc, 0.5, 0.05, cfg, {}, (i, e) => {
      calls.push([i, e]);
      return [];
    });

    expect(calls).toHaveLength(1);
    expect(calls[0][0]).toBe(inc);
    expect(calls[0][1]).toBe(evA);
  });

  it("changes nothing when it finds no violation, or when there is none", () => {
    const withNone = selectRound([cand("A", "prompt", tenTasks("A", 7))], inc, 0.5, 0.05, cfg, {});
    const withEmpty = selectRound([cand("A", "prompt", tenTasks("A", 7))], inc, 0.5, 0.05, cfg, {}, () => []);

    expect(withEmpty.decisions).toEqual(withNone.decisions);
    expect(withEmpty.winner?.variant).toBe("A");
  });
});

describe("candidateComponents", () => {
  it("lists the components of the edits, leaving out the edits that have none", () => {
    const c: Candidate = {
      variant: "A",
      edits: [{ id: "C1", component: "prompt" }, { id: "C2", component: "" }, { id: "C3", component: null }, { id: "C4" }, { id: "C5", component: "memory" }],
    };

    expect(candidateComponents(c)).toEqual(["prompt", "memory"]);
  });

  it("keeps a repeat, and is empty for a candidate with no edit", () => {
    expect(candidateComponents({ variant: "A", edits: [{ component: "memory" }, { component: "memory" }] })).toEqual(["memory", "memory"]);
    expect(candidateComponents({ variant: "A", edits: [] })).toEqual([]);
  });
});
