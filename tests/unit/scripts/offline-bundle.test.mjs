describe("hashLockedFiles", () => {
  // A small package-lock.json: the root project's name and version twice, its dependencies, two installed packages.
  const LOCK = {
    name: "app",
    version: "0.1.0",
    lockfileVersion: 3,
    requires: true,
    packages: {
      "": { name: "app", version: "0.1.0", dependencies: { a: "^1.0.0" }, devDependencies: { d: "^1.0.0" } },
      "node_modules/a": { version: "1.0.0", resolved: "https://registry.npmjs.org/a/-/a-1.0.0.tgz", integrity: "sha512-AAA", dependencies: { b: "^2.0.0" } },
      "node_modules/b": { version: "2.0.0", resolved: "https://registry.npmjs.org/b/-/b-2.0.0.tgz", integrity: "sha512-BBB", optional: true, os: ["linux"] },
    },
  };
  // What the hash of that lock is a hash of: sorted keys at every level, no spaces, and no name or version at the root.
  const LOCK_CANONICAL =
    '{"lockfileVersion":3,"packages":{"":{"dependencies":{"a":"^1.0.0"},"devDependencies":{"d":"^1.0.0"}},' +
    '"node_modules/a":{"dependencies":{"b":"^2.0.0"},"integrity":"sha512-AAA","resolved":"https://registry.npmjs.org/a/-/a-1.0.0.tgz","version":"1.0.0"},' +
    '"node_modules/b":{"integrity":"sha512-BBB","optional":true,"os":["linux"],"resolved":"https://registry.npmjs.org/b/-/b-2.0.0.tgz","version":"2.0.0"}},"requires":true}';
  const lockText = (lock, indent = 2) => `${JSON.stringify(lock, null, indent)}\n`;
  const edited = (change) => {
    const copy = structuredClone(LOCK);
    change(copy);
    return copy;
  };
  // The same lock with the keys of every object in the opposite order.
  const reversed = (value) => {
    if (Array.isArray(value)) return value.map(reversed);
    if (value !== null && typeof value === "object") return Object.fromEntries(Object.entries(value).reverse().map(([key, item]) => [key, reversed(item)]));
    return value;
  };

  // A repo whose lock files and package.json are these texts.
  function repoWith({ lock = lockText(LOCK), cargo = "version = 4\n", packageJson = PACKAGE_JSON } = {}) {
    const root = makeDir("hash");
    write(join(root, "package.json"), packageJson);
    write(join(root, "package-lock.json"), lock);
    write(join(root, "src-tauri", "Cargo.lock"), cargo);
    return root;
  }
  const lockHash = (lock) => hashLockedFiles(repoWith({ lock }))["package-lock.json"];
  const packageJsonWith = (changes) => `${JSON.stringify({ ...JSON.parse(PACKAGE_JSON), ...changes }, null, 2)}\n`;

  it("gives a sha256 for each of the three parts, under the names the manifest uses", () => {
    const hashes = hashLockedFiles(repoWith());
    expect(Object.keys(hashes)).toEqual(["package.json dependencies", "package-lock.json", "src-tauri/Cargo.lock"]);
    for (const hash of Object.values(hashes)) expect(hash).toMatch(/^[0-9a-f]{64}$/);
  });

  it("hashes package-lock.json as canonical JSON without the root's name and version, package.json by its dependency fields, and Cargo.lock as text", () => {
    const hashes = hashLockedFiles(repoWith({ cargo: "cargo text\n" }));
    expect(hashes["package-lock.json"]).toBe(sha256Text(LOCK_CANONICAL));
    expect(hashes["src-tauri/Cargo.lock"]).toBe(sha256Text("cargo text\n"));
    expect(hashes["package.json dependencies"]).toBe(sha256Text('{"dependencies":{"a":"^1.0.0","b":"^2.0.0"},"devDependencies":{"d":"1.0.0"}}'));
  });

  describe("package-lock.json", () => {
    it("has the same hash after a version bump: the name and version at the top and in packages[\"\"] change, nothing else", () => {
      const before = lockHash(lockText(LOCK));
      expect(lockHash(lockText(edited((lock) => { lock.version = "0.1.1"; lock.packages[""].version = "0.1.1"; })))).toBe(before);
      expect(lockHash(lockText(edited((lock) => { lock.name = "renamed"; lock.packages[""].name = "renamed"; })))).toBe(before);
      expect(lockHash(lockText(edited((lock) => { lock.version = "2.0.0"; })))).toBe(before);
      expect(lockHash(lockText(edited((lock) => { lock.packages[""].version = "2.0.0"; })))).toBe(before);
      expect(lockHash(lockText(edited((lock) => { lock.name = "a"; })))).toBe(before);
      expect(lockHash(lockText(edited((lock) => { lock.packages[""].name = "a"; })))).toBe(before);
    });

    it("has the same hash when those four fields are not there at all", () => {
      const before = lockHash(lockText(LOCK));
      const without = edited((lock) => {
        delete lock.name;
        delete lock.version;
        delete lock.packages[""].name;
        delete lock.packages[""].version;
      });
      expect(lockHash(lockText(without))).toBe(before);
    });

    it("has the same hash whatever the order of the keys, the indentation or the line endings", () => {
      const before = lockHash(lockText(LOCK));
      expect(lockHash(lockText(reversed(LOCK)))).toBe(before);
      expect(lockHash(lockText(LOCK, 4))).toBe(before);
      expect(lockHash(lockText(LOCK, "\t"))).toBe(before);
      expect(lockHash(JSON.stringify(LOCK))).toBe(before);
      expect(lockHash(lockText(LOCK).replace(/\n/g, "\r\n"))).toBe(before);
      expect(lockHash(lockText(LOCK).trimEnd())).toBe(before);
      expect(lockHash(`\uFEFF${lockText(LOCK)}`)).toBe(before);
    });

    it("changes with any change to an installed package: its version, URL, integrity, dependencies, platform or name", () => {
      const before = lockHash(lockText(LOCK));
      const differs = (change) => expect(lockHash(lockText(edited(change)))).not.toBe(before);
      differs((lock) => { lock.packages["node_modules/a"].version = "1.0.1"; });
      differs((lock) => { lock.packages["node_modules/a"].integrity = "sha512-CCC"; });
      differs((lock) => { lock.packages["node_modules/a"].resolved = "https://registry.npmjs.org/a/-/a-1.0.1.tgz"; });
      differs((lock) => { lock.packages["node_modules/a"].dependencies.b = "^3.0.0"; });
      differs((lock) => { delete lock.packages["node_modules/a"].dependencies; });
      differs((lock) => { lock.packages["node_modules/b"].os = ["win32"]; });
      differs((lock) => { lock.packages["node_modules/b"].optional = false; });
      // Only the root project's own name and version are left out: an installed package's name is not.
      differs((lock) => { lock.packages["node_modules/a"].name = "other"; });
    });

    it("sorts keys and nothing else: the elements of a list keep their order, so a list in another order is another lock", () => {
      const withOs = (os) => lockHash(lockText(edited((lock) => { lock.packages["node_modules/b"].os = os; })));
      expect(withOs(["linux", "darwin"])).not.toBe(withOs(["darwin", "linux"]));
      expect(withOs(["linux", "darwin"])).toBe(withOs(["linux", "darwin"]));
    });

    it("changes when a package is added or removed, or one is moved to another place", () => {
      const before = lockHash(lockText(LOCK));
      const differs = (change) => expect(lockHash(lockText(edited(change)))).not.toBe(before);
      differs((lock) => { lock.packages["node_modules/c"] = { version: "1.0.0" }; });
      differs((lock) => { delete lock.packages["node_modules/b"]; });
      differs((lock) => { lock.packages["node_modules/x/node_modules/b"] = lock.packages["node_modules/b"]; delete lock.packages["node_modules/b"]; });
    });

    it("changes with the root's dependency fields, lockfileVersion, and any other field of the root", () => {
      const before = lockHash(lockText(LOCK));
      const differs = (change) => expect(lockHash(lockText(edited(change)))).not.toBe(before);
      differs((lock) => { lock.packages[""].dependencies.a = "^1.1.0"; });
      differs((lock) => { lock.packages[""].dependencies.z = "^1.0.0"; });
      differs((lock) => { lock.packages[""].devDependencies.d = "^2.0.0"; });
      differs((lock) => { lock.lockfileVersion = 2; });
      differs((lock) => { lock.requires = false; });
      differs((lock) => { lock.packages[""].license = "MIT"; });
    });

    it("says the file is not JSON, and copes with JSON that is not a lock file", () => {
      expect(messageOf(() => lockHash("not json"))).toMatch(/package-lock\.json is not valid JSON/);
      expect(messageOf(() => lockHash(""))).toMatch(/package-lock\.json is not valid JSON/);
      for (const text of ["null", "[1]", "3", '"text"', "{}", '{ "packages": null }', '{ "packages": { "": null } }', '{ "packages": [] }']) {
        expect(lockHash(text), text).toMatch(/^[0-9a-f]{64}$/);
      }
    });

    it("has the same hash for a real lock file after a version bump, and another after a dependency changes", () => {
      const real = JSON.parse(readFileSync(join(repoRoot, "package-lock.json"), "utf8"));
      const before = lockHash(lockText(real));
      expect(lockHash(lockText(real))).toBe(before);
      const bumped = structuredClone(real);
      bumped.version = "9.8.7";
      bumped.packages[""].version = "9.8.7";
      expect(lockHash(lockText(bumped, 4))).toBe(before);
      const changed = structuredClone(real);
      const [path, entry] = Object.entries(changed.packages).find(([key, item]) => key !== "" && item.version);
      entry.version = `${entry.version}-changed`;
      expect(path).not.toBe("");
      expect(lockHash(lockText(changed))).not.toBe(before);
    });
  });

  describe("Cargo.lock", () => {
    it("has the same hash with CRLF line endings as with LF", () => {
      const lf = hashLockedFiles(repoWith({ cargo: 'version = 4\n\n[[package]]\nname = "x"\n' }));
      const crlf = hashLockedFiles(repoWith({ cargo: 'version = 4\r\n\r\n[[package]]\r\nname = "x"\r\n' }));
      expect(crlf["src-tauri/Cargo.lock"]).toBe(lf["src-tauri/Cargo.lock"]);
    });

    it("does not take a lone CR for a line ending, and still sees a real change", () => {
      const cargoHash = (cargo) => hashLockedFiles(repoWith({ cargo }))["src-tauri/Cargo.lock"];
      const plain = cargoHash("a\nb\n");
      expect(cargoHash("a\rb\n")).not.toBe(plain);
      // Nor is a lone CR simply dropped: a file with one is not the same as one without.
      expect(cargoHash("a\rb\n")).not.toBe(cargoHash("ab\n"));
      // The CR before an LF goes, once: a CR before that one is content, and stays.
      expect(cargoHash("a\r\r\nb\n")).toBe(sha256Text("a\r\nb\n"));
      expect(cargoHash("a\r\nb\r\n")).toBe(sha256Text("a\nb\n"));
      expect(cargoHash("a\nc\n")).not.toBe(plain);
      expect(cargoHash("version = 5\n")).not.toBe(cargoHash("version = 4\n"));
    });

    it("is hashed as text: a change of layout that JSON would not see changes it", () => {
      const cargoHash = (cargo) => hashLockedFiles(repoWith({ cargo }))["src-tauri/Cargo.lock"];
      expect(cargoHash("version = 4\n")).not.toBe(cargoHash("version = 4\n\n"));
    });
  });

  it("gives the same package.json hash when only scripts, the version, other fields or the formatting change", () => {
    const before = hashLockedFiles(repoWith())["package.json dependencies"];
    const same = (packageJson) => expect(hashLockedFiles(repoWith({ packageJson }))["package.json dependencies"]).toBe(before);
    same(packageJsonWith({ scripts: { test: "something else", "offline:bundle": "node x" } }));
    same(packageJsonWith({ version: "9.9.9", description: "new words", engines: { node: ">=22" } }));
    same(JSON.stringify(JSON.parse(PACKAGE_JSON)));
    same(PACKAGE_JSON.replace(/\n/g, "\r\n"));
    same(`\uFEFF${PACKAGE_JSON}`);
  });

  it("gives the same package.json hash when the dependencies are listed in another order", () => {
    const before = hashLockedFiles(repoWith())["package.json dependencies"];
    const reordered = packageJsonWith({ dependencies: { a: "^1.0.0", b: "^2.0.0" } });
    expect(hashLockedFiles(repoWith({ packageJson: reordered }))["package.json dependencies"]).toBe(before);
  });

  it("changes the package.json hash with any dependency field", () => {
    const before = hashLockedFiles(repoWith())["package.json dependencies"];
    const differs = (changes) => expect(hashLockedFiles(repoWith({ packageJson: packageJsonWith(changes) }))["package.json dependencies"]).not.toBe(before);
    differs({ dependencies: { a: "^1.0.0", b: "^2.0.0", c: "^3.0.0" } });
    differs({ dependencies: { a: "^1.0.1", b: "^2.0.0" } });
    differs({ devDependencies: { d: "1.0.1" } });
    differs({ optionalDependencies: { o: "1.0.0" } });
    differs({ peerDependencies: { p: "1.0.0" } });
    differs({ overrides: { a: { nested: "1.0.0" } } });
    differs({ bundleDependencies: ["a"] });
    differs({ bundledDependencies: ["a"] });
  });

  it("says which file is not JSON, and gives null for a file that is missing", () => {
    expect(messageOf(() => hashLockedFiles(repoWith({ packageJson: "{ not json" })))).toMatch(/package\.json is not valid JSON/);
    expect(messageOf(() => hashLockedFiles(repoWith({ lock: "{ not json" })))).toMatch(/package-lock\.json is not valid JSON/);
    const root = repoWith();
    rmSync(join(root, "src-tauri", "Cargo.lock"));
    expect(hashLockedFiles(root)["src-tauri/Cargo.lock"]).toBeNull();
  });

  it("works on the repository's own files, and gives the same hashes each time", () => {
    const hashes = hashLockedFiles(repoRoot);
    for (const hash of Object.values(hashes)) expect(hash).toMatch(/^[0-9a-f]{64}$/);
    expect(hashLockedFiles(repoRoot)).toEqual(hashes);
    expect(hashes["package.json dependencies"]).toBe(sha256Text(dependencyFingerprint(readFileSync(join(repoRoot, "package.json"), "utf8"))));
  });
});

