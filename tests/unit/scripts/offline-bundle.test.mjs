function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

// A repo with the three locked files and an installed node_modules. `packageLock` may be a lock object.
function makeRepo(packageLock = lockOf(entry("a"), entry("b"), entry("@scope/c"))) {
  const root = makeDir("repo");
  write(join(root, "package.json"), '{ "name": "app" }\n');
  write(join(root, "package-lock.json"), JSON.stringify(packageLock, null, 2));
  write(join(root, "src-tauri", "Cargo.lock"), CARGO_LOCK);
  mkdirSync(join(root, "node_modules"));
  return root;
}

// Another checkout of the same source, as on the offline machine: the locked files, no node_modules.
function copyRepo(root) {
  const copy = makeDir("offline-repo");
  for (const name of LOCKED_FILES) write(join(copy, ...name.split("/")), readFileSync(join(root, ...name.split("/")), "utf8"));
  return copy;
}

const LINUX = { platform: "linux", arch: "x64", glibc: "2.39" };

// Deps for a command: the repo, a `tool` that records its calls and does what npm, cargo and git
// would leave behind, and logs that collect what the command prints.
//   host      the machine the command thinks it runs on
//   versions  what npm, cargo and rustc report; a tool left out is missing
//   fail      (name, args) => true makes that call exit 1
function makeDeps(root, { host = LINUX, versions = { npm: "10.9.7", cargo: "1.94.1", rustc: "1.94.1" }, nodeVersion = "22.22.2", fail } = {}) {
  const record = { calls: [], log: [], warn: [], error: [] };
  const tool = (name, args, options = {}) => {
    const call = { name, args, cwd: options.cwd, mode: options.mode };
    record.calls.push(call);
    if (fail?.(name, args)) return { status: 1, stdout: "", stderr: "boom: cargo says something last" };
    if (args[0] === "--version") {
      return versions[name]
        ? { status: 0, stdout: `${name} ${versions[name]} (abc123 2026-01-01)\n`, stderr: "" }
        : { status: null, error: { code: "ENOENT" }, stdout: "", stderr: "" };
    }
    if (name === "git") return { status: 0, stdout: `${COMMIT}\n`, stderr: "" };
    if (name === "npm" && args[0] === "ci") {
      call.scratchHadNpmFiles = ["package.json", "package-lock.json"].every((file) => existsSync(join(options.cwd, file)));
    }
    if (name === "cargo" && args[0] === "vendor") {
      for (const crate of ["log", "serde"]) write(join(args[args.length - 1], crate, "Cargo.toml"), "");
    }
    if (name === "npm" && args[0] === "run" && args[1] === "build:cli") {
      write(join(root, "cli", "dist", "harness-run.mjs"), "// the cli bundle\n");
    }
    if (name === "npm" && args[0] === "run" && args[1] === "build:core") {
      write(join(root, "src-tauri", "target", "release", host.platform === "win32" ? "harness-core.exe" : "harness-core"), "the core binary");
    }
    return { status: 0, stdout: "", stderr: "" };
  };
  const deps = {
    root,
    cwd: root,
    host,
    nodeVersion,
    tool,
    log: (line = "") => record.log.push(line),
    warn: (line) => record.warn.push(line),
    error: (line) => record.error.push(line),
  };
  return { deps, record };
}

const commandLines = (record) => record.calls.map((call) => [call.name, ...call.args].join(" "));

// A finished bundle in `dir`, made by create for `root` on `host`.
function makeBundle(root, dir, host = LINUX, extraArgs = []) {
  const { deps } = makeDeps(root, { host });
  runCreate([dir, ...extraArgs], deps);
  return dir;
}

