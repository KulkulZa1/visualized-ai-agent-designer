function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

// JSON as the lock file hash defines it, written out here on its own: keys sorted at every level, no spaces.
function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value !== null && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

// Where npm's cache keeps a tarball's content, written out here on its own: the code under test
// has its own copy of this rule, and a test that shared it could not tell if the rule were wrong.
function contentFile(cache, integrity) {
  const hex = Buffer.from(integrity.replace(/^sha512-/, ""), "base64").toString("hex");
  return join(cache, "_cacache", "content-v2", "sha512", hex.slice(0, 2), hex.slice(2, 4), hex.slice(4));
}

// package.json with dependencies, and things that are not dependencies.
const PACKAGE_JSON = `${JSON.stringify(
  { name: "app", version: "0.1.0", scripts: { test: "vitest run" }, dependencies: { b: "^2.0.0", a: "^1.0.0" }, devDependencies: { d: "1.0.0" } },
  null,
  2,
)}\n`;

// A repo with the three locked files and an installed node_modules. `packageLock` may be a lock object.
function makeRepo(packageLock = lockOf(entry("a"), entry("b"), entry("@scope/c"))) {
  const root = makeDir("repo");
  write(join(root, "package.json"), PACKAGE_JSON);
  write(join(root, "package-lock.json"), JSON.stringify(packageLock, null, 2));
  write(join(root, "src-tauri", "Cargo.lock"), CARGO_LOCK);
  mkdirSync(join(root, "node_modules"));
  return root;
}

// Another checkout of the same source, as on the offline machine: the locked files, no node_modules.
function copyRepo(root) {
  const copy = makeDir("offline-repo");
  for (const { file } of LOCKED) write(join(copy, ...file.split("/")), readFileSync(join(root, ...file.split("/")), "utf8"));
  return copy;
}

const LINUX = { platform: "linux", arch: "x64", glibc: "2.39" };

// Deps for a command: the repo, a `tool` that records its calls and does what npm, cargo and git
// would leave behind, and logs that collect what the command prints.
//   host      the machine the command thinks it runs on
//   versions  what npm, cargo and rustc report; a tool left out is missing
//   fail      (name, args) => true makes that call exit 1
//   notCached (url) => true makes the fake `npm cache add` leave that tarball out of the cache
function makeDeps(root, { host = LINUX, versions = { npm: "10.9.7", cargo: "1.94.1", rustc: "1.94.1" }, nodeVersion = "22.22.2", fail, notCached } = {}) {
  const record = { calls: [], log: [], warn: [], error: [] };
  const tool = (name, args, options = {}) => {
    const call = { name, args, cwd: options.cwd, mode: options.mode };
    record.calls.push(call);
    if (fail?.(name, args)) return { status: 1, stdout: "", stderr: "boom: cargo says something last" };
    if (args[0] === "--version") {
      return versions[name]
        ? { status: 0, stdout: `${name} ${versions[name]} (abc123 2026-01-01)\n`, stderr: "" }
        : { status: null, error: { code: "ENOENT" }, stdout: "", stderr: "" };
    }
    if (name === "git") return { status: 0, stdout: `${COMMIT}\n`, stderr: "" };
    if (name === "npm" && args[0] === "ci") {
      call.scratchHadNpmFiles = ["package.json", "package-lock.json"].every((file) => existsSync(join(options.cwd, file)));
      // Whether the repo already had its cargo config when npm ci ran.
      call.cargoConfigPresent = existsSync(join(root, ".cargo", "config.toml"));
      const cache = args[args.indexOf("--cache") + 1];
      write(join(cache, "_logs", "ci-debug.log"), "/home/someone/private/path\n");
    }
    if (name === "npm" && args[0] === "cache") {
      // What npm cache add leaves: the tarballs' content under its digest, and a log.
      const cache = args[args.indexOf("--cache") + 1];
      call.sentinelPresent = existsSync(join(dirname(cache), ".offline-bundle"));
      const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
      for (const url of args.filter((arg) => arg.startsWith("https://"))) {
        const found = Object.values(lock.packages).find((item) => item.resolved === url);
        // Content already in the cache stays as it is: cacache does not write the same digest twice.
        if (found?.integrity && !notCached?.(url) && !existsSync(contentFile(cache, found.integrity))) {
          write(contentFile(cache, found.integrity), tarballAt(url));
        }
      }
      write(join(cache, "_logs", "add-debug.log"), "/home/someone/private/path\n");
    }
    if (name === "cargo" && args[0] === "vendor") {
      for (const crate of ["log", "serde"]) write(join(args[args.length - 1], crate, "Cargo.toml"), "");
    }
    if (name === "npm" && args[0] === "run" && args[1] === "build:cli") {
      write(join(root, "cli", "dist", "harness-run.mjs"), "// the cli bundle\n");
    }
    if (name === "npm" && args[0] === "run" && args[1] === "build:core") {
      write(join(root, "src-tauri", "target", "release", host.platform === "win32" ? "harness-core.exe" : "harness-core"), "the core binary");
    }
    return { status: 0, stdout: "", stderr: "" };
  };
  const deps = {
    root,
    cwd: root,
    host,
    nodeVersion,
    tool,
    log: (line = "") => record.log.push(line),
    warn: (line) => record.warn.push(line),
    error: (line) => record.error.push(line),
  };
  return { deps, record };
}

const commandLines = (record) => record.calls.map((call) => [call.name, ...call.args].join(" "));

// A finished bundle in `dir`, made by create for `root` on `host`.
function makeBundle(root, dir, host = LINUX, extraArgs = []) {
  const { deps } = makeDeps(root, { host });
  runCreate([dir, ...extraArgs], deps);
  return dir;
}

