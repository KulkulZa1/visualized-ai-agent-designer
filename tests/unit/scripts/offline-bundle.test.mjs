describe("create: the longest path", () => {
  // A create that puts one file with a long name into the bundle, as a deep crate would.
  function depsWithLongFile(root, host, nameLength) {
    const made = makeDeps(root, { host });
    const tool = made.deps.tool;
    made.deps.tool = (name, args, options) => {
      const result = tool(name, args, options);
      if (name === "cargo" && args[0] === "vendor") write(join(args[args.length - 1], "log", "x".repeat(nameLength)), "");
      return result;
    };
    return made;
  }
  const longestIn = (dir) => Math.max(...readdirSync(dir, { recursive: true }).filter((entry) => statSync(join(dir, String(entry))).isFile()).map((entry) => String(entry).length));

  it("records the length of the longest path inside the bundle, relative to its folder, in the manifest", () => {
    const root = makeRepo();
    const dir = makeDir("bundle");

    runCreate([dir, "--no-binaries"], depsWithLongFile(root, LINUX, 150).deps);

    const manifest = JSON.parse(readFileSync(join(dir, "MANIFEST.json"), "utf8"));
    expect(manifest.longestPathLength).toBe(join("cargo-vendor", "log", "x".repeat(150)).length);
    expect(manifest.longestPathLength).toBe(longestIn(dir));
  });

  it("records the length of an npm cache file when that is the longest path, as it is in a real bundle", () => {
    const root = makeRepo();
    const dir = makeDir("bundle");
    runCreate([dir, "--no-binaries"], makeDeps(root).deps);
    const manifest = JSON.parse(readFileSync(join(dir, "MANIFEST.json"), "utf8"));
    // The npm cache's content files are the longest here: _cacache/content-v2/sha512/ab/cd/<124 hex characters>.
    expect(manifest.longestPathLength).toBe(join("npm-cache", "_cacache", "content-v2", "sha512", "ab", "cd", "x".repeat(124)).length);
    expect(manifest.longestPathLength).toBe(longestIn(dir));
  });

  // The fake bundle holds a path of 230 characters (12 + 1 + 3 + 1 + 213). A POSIX file system takes it,
  // and Windows may not without long paths: the test is for the decision, which is the same everywhere.
  it.skipIf(process.platform === "win32" || tmpdir().length > 50)(
    "warns on Windows, after the work, when the measured longest path is too long for a folder the estimate let through",
    () => {
      const dir = join(makeDir("parent"), "b");
      expect(dir.length + 1 + 170).toBeLessThan(260);
      const { deps, record } = depsWithLongFile(makeRepo(), { platform: "win32", arch: "x64", glibc: null }, 213);

      runCreate([dir, "--no-binaries"], deps);

      const warnings = record.warn.filter((line) => line.includes("Windows stops at 260"));
      expect(warnings).toHaveLength(1);
      expect(warnings[0]).toContain(`the longest path inside the bundle is 230 characters, so paths reach ${dir.length + 1 + 230}`);
    },
  );

  it("does not warn on Windows for a short folder", () => {
    const { deps, record } = depsWithLongFile(makeRepo(), { platform: "win32", arch: "x64", glibc: null }, 20);
    runCreate([join(makeDir("parent"), "b"), "--no-binaries"], deps);
    expect(record.warn.filter((line) => line.includes("Windows stops at 260"))).toEqual([]);
  });
});

