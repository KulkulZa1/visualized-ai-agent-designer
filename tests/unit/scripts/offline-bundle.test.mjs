// Runs the script the way a person does. Only what refuses or skips everything, so that no npm or
// cargo is started: what a step would start is what the tests above check.
describe("scripts/offline-bundle.mjs as a command", () => {
  const script = join(repoRoot, "scripts", "offline-bundle.mjs");
  const run = (args, options = {}) => spawnSync(process.execPath, [options.script ?? script, ...args], { encoding: "utf8", cwd: options.cwd ?? repoRoot });

  it("prints the usage for --help", () => {
    const result = run(["--help"]);
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("Usage: node scripts/offline-bundle.mjs <command> [options]");
    expect(result.stdout).toContain("Steps: tsc, vitest, cargo-core, cargo-app, build-cli, build-core, vite-build.");
  });

  it("exits 1 with the usage for a command it does not have", () => {
    const result = run(["bundle"]);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("Usage:");
  });

  it("verify with every step skipped runs nothing and exits 0", () => {
    const result = run(["verify", "--skip", "tsc,vitest,cargo-core,cargo-app,build-cli,build-core,vite-build"]);
    expect(result.status).toBe(0);
    expect(result.stdout).toMatch(/tsc\s+skipped/);
    expect(result.stdout).toContain("(7 skipped)");
  });

  it("create refuses a folder that is not empty: exit 1, one line on stderr, nothing changed", () => {
    const dir = makeDir("bundle");
    write(join(dir, "old.txt"), "keep me");

    const result = run(["create", dir]);

    expect(result.status).toBe(1);
    expect(result.stderr).toMatch(/^offline-bundle: .* is not empty\. .*--force/);
    expect(result.stderr.trim().split("\n")).toHaveLength(1);
    expect(result.stdout).toBe("");
    expect(readdirSync(dir)).toEqual(["old.txt"]);
  });

  it("setup leaves a .cargo/config.toml it did not write alone: exit 1, file unchanged", () => {
    // A copy of the script in a scratch repo, because setup works on the repo the script is in.
    const source = makeRepo();
    const bundle = makeBundle(source, makeDir("bundle"), LINUX, ["--no-binaries"]);
    const offline = copyRepo(source);
    mkdirSync(join(offline, "scripts"));
    for (const name of ["offline-bundle.mjs", "offline-bundle-lib.mjs"]) copyFileSync(join(repoRoot, "scripts", name), join(offline, "scripts", name));
    const theirs = "[build]\njobs = 2\n";
    write(join(offline, ".cargo", "config.toml"), theirs);

    const result = run(["setup", bundle], { script: join(offline, "scripts", "offline-bundle.mjs"), cwd: offline });

    expect(result.status).toBe(1);
    expect(result.stderr).toContain("was not written by this script, so it is left alone");
    expect(readFileSync(join(offline, ".cargo", "config.toml"), "utf8")).toBe(theirs);
    expect(existsSync(join(offline, "node_modules"))).toBe(false);
  });
});
