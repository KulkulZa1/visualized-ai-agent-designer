// node_modules with the three packages verify runs, each declaring its command as npm would.
function installTools(root) {
  const bins = { typescript: { tsc: "./bin/tsc" }, vitest: { vitest: "./vitest.mjs" }, vite: { vite: "bin/vite.js" } };
  for (const [name, bin] of Object.entries(bins)) write(join(root, "node_modules", name, "package.json"), JSON.stringify({ name, bin }));
}

describe("verify", () => {
  it("runs the seven steps in order, and prints a table with each exit status", () => {
    const root = makeRepo();
    installTools(root);
    const { deps, record } = makeDeps(root);

    expect(runVerify([], deps)).toBe(0);

    const node = (pkg, file) => ["node", join(root, "node_modules", pkg, file)];
    expect(record.calls.map((call) => [call.name, ...call.args])).toEqual([
      [...node("typescript", "bin/tsc"), "--noEmit"],
      [...node("vitest", "vitest.mjs"), "run"],
      ["cargo", "test", "--manifest-path", "src-tauri/Cargo.toml", "--no-default-features", "--features", "core"],
      ["cargo", "test", "--manifest-path", "src-tauri/Cargo.toml"],
      ["npm", "run", "build:cli"],
      ["npm", "run", "build:core"],
      [...node("vite", "bin/vite.js"), "build"],
    ]);
    for (const call of record.calls) expect(call.cwd).toBe(root);

    const table = record.log.filter((line) => /^(tsc|vitest|cargo-core|cargo-app|build-cli|build-core|vite-build)\s+PASS\s+0\s/.test(line));
    expect(table).toHaveLength(7);
    expect(record.log.join("\n")).toContain("verify: every step that ran passed.");
  });

  it("keeps going after a failing step, reports it with its exit status, and exits 1", () => {
    const root = makeRepo();
    installTools(root);
    const { deps, record } = makeDeps(root, { fail: (name, args) => name === "cargo" && args.includes("--features") });

    expect(runVerify([], deps)).toBe(1);

    expect(record.calls).toHaveLength(7);
    const lines = record.log;
    expect(lines.find((line) => line.startsWith("cargo-core"))).toMatch(/^cargo-core\s+FAIL\s+1\s/);
    expect(lines.find((line) => line.startsWith("vite-build"))).toMatch(/^vite-build\s+PASS\s+0\s/);
    expect(lines.find((line) => line.startsWith("tsc"))).toMatch(/^tsc\s+PASS/);
    expect(lines.join("\n")).toContain("verify: 1 of 7 steps failed: cargo-core.");
  });

  it("skips the steps named by --skip and shows them as skipped", () => {
    const root = makeRepo();
    installTools(root);
    const { deps, record } = makeDeps(root);

    expect(runVerify(["--skip", "cargo-app,vitest"], deps)).toBe(0);

    expect(record.calls).toHaveLength(5);
    expect(commandLines(record).some((line) => line === "cargo test --manifest-path src-tauri/Cargo.toml")).toBe(false);
    expect(record.log.find((line) => line.startsWith("cargo-app"))).toMatch(/^cargo-app\s+skipped\s+-\s+-$/);
    expect(record.log.join("\n")).toContain("(2 skipped)");
  });

  it("does not skip a failure: a failing step is still a failing verify when others are skipped", () => {
    const root = makeRepo();
    installTools(root);
    const { deps } = makeDeps(root, { fail: (name, args) => name === "npm" && args[1] === "build:cli" });
    expect(runVerify(["--skip=cargo-app"], deps)).toBe(1);
  });

  it("refuses a step name it does not know", () => {
    const root = makeRepo();
    const { deps, record } = makeDeps(root);
    expect(messageOf(() => runVerify(["--skip", "cargo-ap"], deps))).toMatch(/Unknown step "cargo-ap".*tsc, vitest, cargo-core, cargo-app, build-cli, build-core, vite-build/);
    expect(record.calls).toEqual([]);
  });

  it("fails a step whose tool is not installed and goes on, instead of trying to download it", () => {
    const root = makeRepo();
    installTools(root);
    rmSync(join(root, "node_modules", "typescript"), { recursive: true });
    const { deps, record } = makeDeps(root);

    expect(runVerify([], deps)).toBe(1);

    expect(commandLines(record).some((line) => line.includes("typescript"))).toBe(false);
    expect(record.calls).toHaveLength(6);
    expect(record.error.join("\n")).toMatch(/typescript is not installed in node_modules/);
    expect(record.log.find((line) => line.startsWith("tsc"))).toMatch(/^tsc\s+FAIL\s+-\s/);
  });

  it("fails a step that cannot start, and says why", () => {
    const root = makeRepo();
    installTools(root);
    const { deps, record } = makeDeps(root);
    const tool = deps.tool;
    deps.tool = (name, args, options) => (name === "cargo" ? { status: null, error: { code: "ENOENT" }, stdout: "", stderr: "" } : tool(name, args, options));

    expect(runVerify(["--skip", "cargo-app"], deps)).toBe(1);

    expect(record.log.join("\n")).toContain("cargo-core: could not start: ENOENT");
  });
});

